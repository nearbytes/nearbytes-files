#!/usr/bin/env node
/**
 * Render LaTeX fragments for the paper from bench-report.json
 *
 *   node scripts/render-benchmark-figures.mjs --report bench-report.json --outdir ../paper-nearbytes-hypercore/figures
 */

import { readFile, writeFile, mkdir } from 'fs/promises';
import path from 'path';

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

function esc(s) {
  return String(s)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/[&%$#_{}]/g, (c) => `\\${c}`)
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

function fmtMs(v) {
  if (v === null || v === undefined) return '---';
  return v >= 1000 ? `${(v / 1000).toFixed(2)}\\,s` : `${Math.round(v)}\\,ms`;
}

function fmtMbps(v) {
  if (v === null || v === undefined) return '---';
  return `${v.toFixed(2)}`;
}

const reportPath = arg('--report', 'bench-report.json');
const outDir = arg('--outdir', path.join(process.cwd(), 'benchmark-output'));
const report = JSON.parse(await readFile(reportPath, 'utf-8'));

await mkdir(outDir, { recursive: true });

const latencyRows = (report.latencyTable ?? [])
  .map(
    (r) =>
      `${esc(r.sizeLabel)} & ${r.n ?? 0} & ${fmtMs(r.p50)} & ${fmtMs(r.p95)} & ${fmtMs(r.mean)} \\\\`,
  )
  .join('\n');

const resultsTable = `% Auto-generated by nearbytes-files/scripts/render-benchmark-figures.mjs
\\begin{table}[t]
\\centering
\\caption{Preliminary one-way convergence latency (Mac $\\rightarrow$ \\texttt{pc-ciancia}) for friend carriage v0 after swarm formation. Payloads are encrypted volume files; latency is wall-clock from sender \\texttt{addFile} return to receiver first \\texttt{listFiles} hit ($n=5$ per size).}
\\label{tab:bench-latency}
\\small
\\begin{tabular}{@{}lrrrr@{}}
\\toprule
Payload & $n$ & $p_{50}$ & $p_{95}$ & mean \\\\
\\midrule
${latencyRows}
\\bottomrule
\\end{tabular}
\\end{table}
`;

const swarmSender = report.swarmFormation?.senderMs ?? 0;
const swarmRecv = report.swarmFormation?.receiverMs ?? 0;
const tpGoodput = report.throughput?.receiverGoodputMbps ?? 0;

const mscFigure = `% Auto-generated MSC-style collaboration diagram
\\begin{figure}[t]
\\centering
\\begin{tikzpicture}[font=\\small, node distance=0.55cm and 3.2cm]
  \\node[draw, rounded corners, minimum width=2.6cm] (alice) {Alice (Mac)};
  \\node[draw, rounded corners, minimum width=2.6cm, right=of alice] (bob) {Bob (pc-ciancia)};
  \\node[draw, rounded corners, minimum width=2.2cm, below=0.9cm of alice] (swarm) {Hyperswarm+mDNS};
  \\draw[dashed,->] (alice) -- node[above,sloped]{\\topic(profile)} (swarm);
  \\draw[dashed,->] (bob) -- node[above,sloped]{\\topic(profile)} (swarm);
  \\draw[->] (swarm) -- node[left]{duplex} (alice);
  \\draw[->] (swarm) -- node[right]{duplex} (bob);
  \\node[below=0.15cm of alice] {\\footnotesize $t_0$: discovery start};
  \\node[below=0.15cm of bob] {\\footnotesize $t_0'$: discovery start};
  \\node[above=0.05cm of swarm] {\\footnotesize peer at $+${swarmSender}\\,ms / $+${swarmRecv}\\,ms};
\\end{tikzpicture}
\\caption{Measured collaboration timeline (warmup). Both nodes join friend profile topics, publish \\texttt{nb.identity.record.v1}, then anti-entropy over \\texttt{nearbytes.sync.v1}. Swarm association observed at $+${swarmSender}\\,ms (Alice) and $+${swarmRecv}\\,ms (Bob) from respective discovery start markers.}
\\label{fig:bench-msc}
\\end{figure}
`;

const senderMarkers = (report.senderMarkers ?? []).slice(0, 12);
const recvMarkers = (report.receiverMarkers ?? []).slice(0, 12);

const timelineLines = [
  ...senderMarkers.map((m) => `Alice & ${m.t} & ${esc(m.event)} & ${esc(JSON.stringify(m.fields))} \\\\`),
  ...recvMarkers.map((m) => `Bob & ${m.t} & ${esc(m.event)} & ${esc(JSON.stringify(m.fields))} \\\\`),
].join('\n');

const timelineFigure = `% Auto-generated event timeline from sync activity markers
\\begin{figure}[t]
\\centering
\\small
\\begin{tabular}{@{}llll@{}}
\\toprule
Host & wall ms & event & detail \\\\
\\midrule
${timelineLines || '--- & --- & --- & --- \\\\'}
\\bottomrule
\\end{tabular}
\\caption{Excerpt of structured \\texttt{bench} markers appended to \\texttt{sync/activity.log} during the run (wall-clock \\texttt{t} field).}
\\label{fig:bench-timeline}
\\end{figure}
`;

const recvTail = (report.receiverReceptionTail ?? []).slice(-15);
const eventStreamFigure = `% Auto-generated reception journal tail
\\begin{figure}[t]
\\centering
\\begin{lstlisting}[basicstyle=\\ttfamily\\scriptsize,breaklines=true,frame=single]
${recvTail.map((l) => esc(l)).join('\n')}
\\end{lstlisting}
\\caption{Tail of Bob's local reception journal (\\texttt{sync/reception.jsonl}) after the benchmark---append-only \\texttt{ObjectRef} entries driving \\texttt{global\\_delta}.}
\\label{fig:bench-reception}
\\end{figure}
`;

const summaryTex = `% Auto-generated benchmark summary
\\paragraph{Preliminary results (${esc(report.generatedAt?.slice(0, 10) ?? '')}).}
Two Linux peers (Mac and \\texttt{pc-ciancia}) ran Implementation~0 with well-known profile secrets and a shared bench volume. Swarm formation (first \\texttt{peer-connected} marker) occurred at $+${swarmSender}\\,ms$ (sender) and $+${swarmRecv}\\,ms$ (receiver). Sustained friend carriage goodput on the receiver side reached ${fmtMbps(tpGoodput)}\\,Mb/s for $12\\times1$\\,MiB encrypted files after association (Table~\\ref{tab:bench-latency}, Figures~\\ref{fig:bench-msc}--\\ref{fig:bench-reception}).
`;

await writeFile(path.join(outDir, 'benchmark-results-table.tex'), resultsTable);
await writeFile(path.join(outDir, 'benchmark-msc.tex'), mscFigure);
await writeFile(path.join(outDir, 'benchmark-timeline.tex'), timelineFigure);
await writeFile(path.join(outDir, 'benchmark-reception.tex'), eventStreamFigure);
await writeFile(path.join(outDir, 'benchmark-summary.tex'), summaryTex);

console.log(`Wrote LaTeX fragments to ${outDir}`);
